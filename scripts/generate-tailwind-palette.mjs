// Generates src/core/convert/tailwind-palette.ts from the installed Tailwind packages, so color
// matching uses Tailwind's real palettes instead of hand-copied values.
// Run: node scripts/generate-tailwind-palette.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// v4: CSS custom properties in theme.css, e.g. `--color-red-500: oklch(63.7% 0.237 25.331);`
const v4Version = require('tailwindcss/package.json').version;
const themeCss = fs.readFileSync(require.resolve('tailwindcss/theme.css'), 'utf8');
const v4 = {};
for (const [, name, value] of themeCss.matchAll(/--color-([a-z]+(?:-\d+)?):\s*([^;]+);/g)) {
  v4[name] = value.trim();
}

// v3: nested JS object, e.g. colors.red[500] = '#ef4444'. Skip deprecated aliases (they warn).
const v3Version = require('tailwindcss-v3/package.json').version;
const colorsV3 = require('tailwindcss-v3/colors');
const DEPRECATED = new Set(['lightBlue', 'warmGray', 'trueGray', 'coolGray', 'blueGray']);
const v3 = {};
for (const name of Object.keys(colorsV3)) {
  if (DEPRECATED.has(name)) continue;
  const value = colorsV3[name];
  if (typeof value === 'string') {
    if (value.startsWith('#')) v3[name] = value;
  } else {
    for (const [shade, hex] of Object.entries(value)) v3[`${name}-${shade}`] = hex;
  }
}

const literal = (obj) =>
  `{\n${Object.entries(obj)
    .map(([k, v]) => `  '${k}': '${v}',`)
    .join('\n')}\n}`;

const out = `// Generated by scripts/generate-tailwind-palette.mjs from tailwindcss@${v4Version} and
// tailwindcss@${v3Version}. Do not edit by hand.

/** Tailwind v4 default colors (OKLCH, as defined in theme.css). */
export const PALETTE_V4: Record<string, string> = ${literal(v4)};

/** Tailwind v3 default colors (hex). */
export const PALETTE_V3: Record<string, string> = ${literal(v3)};
`;

const target = path.join(root, 'src/core/convert/tailwind-palette.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`v4: ${Object.keys(v4).length} colors, v3: ${Object.keys(v3).length} colors -> ${path.relative(root, target)}`);
